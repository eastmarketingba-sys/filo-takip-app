function t(key, vars){
  let str = (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS.tr[key] || key;
  if(vars){
    for(const k in vars) str = str.split('{{'+k+'}}').join(vars[k]);
  }
  return str;
}

function tDays(n){
  if(currentLang==='en') return n===1 ? '1 day' : `${n} days`;
  if(currentLang==='bs') return n===1 ? '1 dan' : `${n} dana`;
  return `${n} gün`;
}

function tRentals(n){
  if(currentLang==='en') return n===1 ? '1 rental' : `${n} rentals`;
  if(currentLang==='bs') return n===1 ? '1 iznajmljivanje' : `${n} iznajmljivanja`;
  return `${n} kiralama`;
}

function localeForLang(){
  if(currentLang==='en') return 'en-US';
  if(currentLang==='bs') return 'bs-BA';
  return 'tr-TR';
}

function setLang(lang){
  currentLang = TRANSLATIONS[lang] ? lang : 'tr';
}

function applyStaticTranslations(){
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el=>{ el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{ el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll('[data-i18n-title]').forEach(el=>{ el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-html]').forEach(el=>{ el.innerHTML = t(el.dataset.i18nHtml); });
}
